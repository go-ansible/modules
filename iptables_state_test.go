// hybridConn fakes Exec for whatever commands are listed in `on` and
// falls back to a REAL local.Exec for everything else (in particular
// `test -e ...`, used by fetchIfExists/pathExists), while Put/Fetch/
// Remove/TempPath/Close all go to the real remoteexec.Local — needed
// for iptables_state.go's tests, which round-trip real file content
// through writeRemote/fetchIfExists and so need those to actually work
// against the temp files these tests create, unlike fakeConn's Put/
// Fetch, which are no-ops.
type hybridConn struct {
	local *remoteexec.Local
	on    map[string]remoteexec.Result
}

func newHybridConn(on map[string]remoteexec.Result) *hybridConn {
	return &hybridConn{local: local(), on: on}
}

func (h *hybridConn) Exec(ctx context.Context, cmd string, stdin io.Reader) (remoteexec.Result, error) {
	if res, ok := h.on[cmd]; ok {
		return res, nil
	}
	return h.local.Exec(ctx, cmd, stdin)
}
func (h *hybridConn) Put(ctx context.Context, localPath, remotePath string, opts remoteexec.PutOptions) error {
	return h.local.Put(ctx, localPath, remotePath, opts)
}
func (h *hybridConn) Fetch(ctx context.Context, remotePath, localPath string) error {
	return h.local.Fetch(ctx, remotePath, localPath)
}
func (h *hybridConn) Remove(ctx context.Context, remotePath string) error {
	return h.local.Remove(ctx, remotePath)
}
func (h *hybridConn) TempPath(base string) string { return h.local.TempPath(base) }
func (h *hybridConn) Close() error                { return h.local.Close() }

var _ remoteexec.Connection = (*hybridConn)(nil)

const iptablesSaveOut = "# Generated by iptables-save v1.8.7 on Mon Jan  1 00:00:00 2024\n" +
	"*filter\n" +
	":INPUT ACCEPT [10:1000]\n" +
	":FORWARD ACCEPT [0:0]\n" +
	":OUTPUT ACCEPT [5:500]\n" +
	"-A INPUT -i lo -j ACCEPT\n" +
	"COMMIT\n" +
	"# Completed on Mon Jan  1 00:00:00 2024\n"

func TestModuleIptablesStateSavedNewFile(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "iptables.rules")
	conn := newHybridConn(map[string]remoteexec.Result{
		"command -v iptables-save >/dev/null 2>&1 && command -v iptables-restore >/dev/null 2>&1": {RC: 0},
		"iptables-save": {RC: 0, Stdout: iptablesSaveOut},
	})
	res, err := moduleIptablesState(context.Background(), conn, map[string]any{"state": "saved", "path": path})
	if err != nil {
		t.Fatal(err)
	}
	if !res.Changed {
		t.Fatalf("res = %+v", res)
	}
	tables := res.Extra["tables"].(map[string][]string)
	if _, ok := tables["filter"]; !ok {
		t.Fatalf("tables = %#v", tables)
	}
}

func TestModuleIptablesStateSavedIdempotent(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "iptables.rules")
	// pre-write the EXACT content the module would produce (counters
	// zeroed, timestamps stripped down to the bare comment, but not
	// removed entirely) so the second run is a no-op.
	expected := "# Generated by iptables-save v1.8.7\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n" +
		":OUTPUT ACCEPT [0:0]\n-A INPUT -i lo -j ACCEPT\nCOMMIT\n# Completed\n"
	if err := os.WriteFile(path, []byte(expected), 0o644); err != nil {
		t.Fatal(err)
	}
	conn := newHybridConn(map[string]remoteexec.Result{
		"command -v iptables-save >/dev/null 2>&1 && command -v iptables-restore >/dev/null 2>&1": {RC: 0},
		"iptables-save": {RC: 0, Stdout: iptablesSaveOut},
	})
	res, err := moduleIptablesState(context.Background(), conn, map[string]any{"state": "saved", "path": path})
	if err != nil {
		t.Fatal(err)
	}
	if res.Changed {
		t.Fatalf("res = %+v, want unchanged: counters/timestamp differences must not count", res)
	}
}

