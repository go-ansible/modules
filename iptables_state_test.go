func TestIptablesFilterFormatStripsTimestampsAndCounters(t *testing.T) {
	lines := iptablesFilterFormat(iptablesSaveOut, false)
	for _, l := range lines {
		if l == "# Generated by iptables-save v1.8.7 on Mon Jan  1 00:00:00 2024" {
			t.Fatal("timestamp should be stripped")
		}
	}
	found := false
	for _, l := range lines {
		if l == ":INPUT ACCEPT [0:0]" {
			found = true
		}
	}
	if !found {
		t.Fatalf("counters should be zeroed: %v", lines)
	}
}

func TestIptablesFilterFormatKeepsCounters(t *testing.T) {
	lines := iptablesFilterFormat(iptablesSaveOut, true)
	found := false
	for _, l := range lines {
		if l == ":INPUT ACCEPT [10:1000]" {
			found = true
		}
	}
	if !found {
		t.Fatalf("counters should be preserved when counters=true: %v", lines)
	}
}

